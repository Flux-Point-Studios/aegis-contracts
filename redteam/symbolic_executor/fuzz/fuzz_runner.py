"""Pytest-compatible fuzz runner.

Drives `differential.run_pair` for N seeds per (branch, property)
pair, optionally piping the Aiken-mappable inputs to a subprocess that
runs `aiken check --match-tests fuzz_*` against generated test source.

Two operating modes:
  * `fuzz_pair`           — Tier 1 only. Pure Python; fast.
  * `fuzz_pair_with_aiken` — Tier 1 + Tier 2 (subprocess to aiken).

Tier-2 is opt-in because subprocess-to-aiken is slow (~3-5s per call).
The Tier-2 path also requires `aiken` to be on PATH and the contracts
project to compile cleanly.
"""

